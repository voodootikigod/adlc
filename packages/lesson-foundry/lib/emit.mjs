// File emission for lesson-foundry — generates defense artifacts.
// Pure functions that return { path, content } pairs; caller writes them.

import { extname } from 'node:path';
import { clusterName, clusterId, clusterMembers, extractLiteralPattern, escapeRegex } from './route.mjs';

const DEFAULT_INCLUDE_EXTS = ['.mjs', '.js', '.ts', '.tsx'];

export function collectIncludeGlobs(findings) {
  const exts = new Set(DEFAULT_INCLUDE_EXTS);
  for (const f of findings ?? []) {
    if (typeof f?.file === 'string') {
      const ext = extname(f.file);
      if (/^\.[A-Za-z0-9_-]+$/.test(ext)) exts.add(ext);
    }
  }
  return [...exts].map((ext) => `--include="*${ext}"`).join(' ');
}

/**
 * Collapse every line terminator and control character to a space. Finding
 * text is reviewer- or model-authored; a line break inside it would end the
 * generated script's comment (making the rest executable) or start a new
 * SKILL.md frontmatter key.
 */
export function oneLine(text) {
  return String(text).replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, ' ');
}

function safeArtifactStem(name) {
  const cleaned = oneLine(name).trim().replace(/[\\/]+/g, '-').replace(/^\.+/, '');
  return cleaned || 'cluster';
}

/**
 * Build the grep-gate JSON descriptor for a LINT cluster.
 * Returns { path, content } where path is relative to outDir.
 */
export function buildLintDescriptor(name, findings) {
  const safeName = safeArtifactStem(name);
  const literal = extractLiteralPattern(findings);
  const pattern = literal ? escapeRegex(literal) : clusterName(findings).replace(/-/g, '.*');

  const descriptor = {
    // Stable, prose-independent cluster key. The gate credits the descriptor by
    // this id even if the slug-derived filename below has since drifted or been
    // renamed during refinement. Kept first so it survives a hand-edit at the top.
    id: clusterId(findings),
    // Durable banking identity: overlap with these survives growth AND merges.
    members: clusterMembers(findings),
    name: safeName,
    pattern,
    paths: ['**'],
    message: `lesson-foundry: recurring finding — ${findings[0]?.desc ?? safeName}`,
  };

  return {
    path: `${safeName}.lint.json`,
    content: JSON.stringify(descriptor, null, 2) + '\n',
  };
}

/**
 * Build the runnable check script for a LINT cluster.
 * Returns { path, content }.
 */
export function buildCheckScript(name, findings) {
  const literal = extractLiteralPattern(findings);
  const pattern = literal ? escapeRegex(literal) : clusterName(findings).replace(/-/g, '.*');
  const safeName = safeArtifactStem(name);
  const desc = oneLine(findings[0]?.desc ?? safeName).replace(/`/g, "'");

  // The gate must never trip on itself. We exclude VCS/dependency dirs and the
  // generated lessons output directory, and filter out ONLY this script's own
  // canonical path (`SELF_PATH`) so fnmatch metacharacters in `name` cannot
  // widen `--exclude` and same-named files elsewhere in the repo are still checked.
  const includeFlags = collectIncludeGlobs(findings);

  const content = `#!/usr/bin/env node
// Auto-generated by lesson-foundry — do not edit manually.
// Grep gate: ${desc}

import { execFileSync } from 'node:child_process';
import { accessSync, constants as fsConstants, lstatSync, realpathSync, statSync } from 'node:fs';
import { delimiter, isAbsolute, join, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';

const PATTERN = ${JSON.stringify(pattern)};
const ROOT = realpathSync(resolve('.'));
// This generated script itself contains PATTERN (above and in its header
// comment). Exclude only its own canonical file path so same-named files
// elsewhere in the repo are still scanned.
const SELF_PATH = realpathSync(fileURLToPath(import.meta.url));
const INCLUDE_GLOBS = '${includeFlags.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}';
const INCLUDE_ARGS = INCLUDE_GLOBS.split(' ').filter(Boolean).map((flag) => flag.replace(/"/g, ''));

function isInsideRoot(p) {
  return p === ROOT || p.startsWith(ROOT + sep);
}

function resolveTrustedGrep(pathStr = process.env.PATH) {
  const selfUid = typeof process.getuid === 'function' ? process.getuid() : null;
  const binName = process.platform === 'win32' ? 'grep.exe' : 'grep';
  for (const dir of String(pathStr ?? '').split(delimiter)) {
    if (!dir || dir === '.' || !isAbsolute(dir) || /(?:^|[\\\\/])node_modules(?:[\\\\/]|$)/.test(dir)) continue;
    let dirReal;
    let dirSt;
    try {
      dirReal = realpathSync(dir);
      dirSt = statSync(dirReal);
    } catch {
      continue;
    }
    if (!dirSt.isDirectory() || isInsideRoot(resolve(dir)) || isInsideRoot(dirReal)) continue;
    if (process.platform !== 'win32' && (dirSt.mode & 0o002) !== 0) continue;
    for (const name of process.platform === 'win32' ? [binName, 'grep'] : ['grep']) {
      const candidate = join(dir, name);
      try {
        const linkSt = lstatSync(candidate);
        const candReal = realpathSync(candidate);
        if (isInsideRoot(candReal) || /(?:^|[\\\\/])node_modules(?:[\\\\/]|$)/.test(candReal)) continue;
        const st = statSync(candReal);
        if (!st.isFile()) continue;
        if (process.platform !== 'win32') {
          accessSync(candReal, fsConstants.X_OK);
          if ((st.mode & 0o002) !== 0) continue;
        }
        if (selfUid !== null && st.uid !== selfUid) {
          if (linkSt.uid !== 0 || st.uid !== 0 || (st.mode & 0o022) !== 0 || dirSt.uid !== 0 || (dirSt.mode & 0o022) !== 0) continue;
        }
        return candidate;
      } catch {
        continue;
      }
    }
  }
  return null;
}

const GREP_BIN = resolveTrustedGrep();
if (!GREP_BIN) {
  console.error(${JSON.stringify(`check-${safeName}: grep error:`)}, 'no trusted grep binary found on PATH');
  process.exit(2);
}

let output = '';
try {
  output = execFileSync(
    GREP_BIN,
    [
      '-rn',
      ...INCLUDE_ARGS,
      '--exclude-dir=node_modules',
      '--exclude-dir=.git',
      '--exclude-dir=.adlc',
      '-E',
      '-e',
      PATTERN,
      '--',
      ROOT,
    ],
    { encoding: 'utf8', stdio: ['pipe', 'pipe', 'pipe'] }
  );
} catch (err) {
  // grep exits 1 with empty stderr when no match — that's the PASS case.
  // A missing grep binary (ENOENT, status null) or exit 1 with stderr fails closed.
  const stderrText = String(err.stderr ?? '').trim();
  if (err.status === 1 && !err.code && stderrText === '') {
    console.log(${JSON.stringify(`check-${safeName}: no matches found — PASS`)});
    process.exit(0);
  }
  // grep exits 2 on error, or execFileSync failed to invoke grep
  console.error(${JSON.stringify(`check-${safeName}: grep error:`)}, stderrText || err.message);
  process.exit(2);
}

// Drop only lines belonging to this exact gate script file (<SELF_PATH>:<line>:).
const lines = output
  .split('\\n')
  .filter((l) => l.trim() && !l.startsWith(\`\${SELF_PATH}:\`));

if (lines.length > 0) {
  console.error(${JSON.stringify(`check-${safeName}: FAIL — pattern found in repo:`)});
  console.error(lines.join('\\n'));
  process.exit(2);
}

console.log(${JSON.stringify(`check-${safeName}: no matches found — PASS`)});
process.exit(0);
`;

  return {
    path: `check-${safeName}.mjs`,
    content,
  };
}

const YAML_NEEDS_QUOTES_RE = /(?:^[-?:,[\]{}#&*!|>'"%@`]|:\s|:$|\s#)/;

function safeFrontmatterScalar(value, fallback = 'pattern') {
  const cleaned = oneLine(value).trim();
  const base = !cleaned || cleaned === '---' || cleaned === '...' ? fallback : cleaned;
  return YAML_NEEDS_QUOTES_RE.test(base) ? JSON.stringify(base) : base;
}

/**
 * Build a SKILL.md stub for a SKILL cluster.
 * Returns { path, content }.
 */
export function buildSkillStub(name, findings, llmRefinement) {
  const safeName = safeArtifactStem(name);
  const count = findings.length;
  const category = safeFrontmatterScalar(findings[0]?.category ?? 'pattern', 'pattern');
  const desc = safeFrontmatterScalar(llmRefinement?.description ?? findings[0]?.desc ?? safeName, safeName);
  const rule = llmRefinement?.rule ?? `Avoid: ${findings[0]?.desc ?? safeName}`;
  const displayName = safeFrontmatterScalar(llmRefinement?.name ?? safeName, 'lesson-skill');

  // Collect evidence quotes
  const evidenceQuotes = findings
    .slice(0, 3)
    .map((f) => {
      const parts = [];
      if (f.file) parts.push(`file: ${f.file}`);
      if (f.line) parts.push(`line: ${f.line}`);
      if (f.desc) parts.push(`finding: ${f.desc}`);
      return parts.join(', ');
    })
    .filter(Boolean);

  const evidenceSection = evidenceQuotes.length
    ? evidenceQuotes.map((e) => `- ${e}`).join('\n')
    : '- (no specific file evidence recorded)';

  const content = `---
name: ${displayName}
description: ${desc}
category: ${category}
mined-from: ${count} findings
cluster-id: ${clusterId(findings)}
cluster-members: ${clusterMembers(findings).join(' ')}
triggers:
  - ${category}
  - recurring-finding
  - lesson-foundry
---

# ${displayName}

## Rule

${rule}

## Evidence

Mined from ${count} finding${count === 1 ? '' : 's'}:

${evidenceSection}

## Rationale

This skill was auto-generated by lesson-foundry from recurring prosecution findings.
Apply this rule proactively to prevent re-encountering the same issue.
`;

  return {
    path: `${safeName}.SKILL.md`,
    content,
  };
}

/**
 * Build the interrogation template line for a SPEC-GAP cluster.
 * Returns a markdown line to append to interrogation-template.md.
 */
export function buildSpecGapLine(name, findings) {
  const count = findings.length;
  const desc = oneLine(findings[0]?.desc ?? name);
  const category = oneLine(findings[0]?.category ?? 'unknown');
  const safeName = oneLine(name);
  const id = clusterId(findings);
  // Two markers: the human-readable slug (legacy, kept for back-compat) and the
  // stable cluster-id. The gate credits either, so rewording the question — even
  // dropping the slug annotation — cannot orphan the lesson as long as the id
  // marker survives.
  const members = clusterMembers(findings).join(' ');
  return `- [ ] **[${category}]** ${desc} *(recurring in ${count} finding${count === 1 ? '' : 's'}, cluster: ${safeName}, cluster-id: ${id}, cluster-members: ${members})*\n`;
}

/**
 * Plan all emissions for a set of clusters.
 * Returns array of { cluster, route, files: [{path, content}], destination }.
 * outDir prefix is applied to paths.
 * llmRefinements: Map<clusterIndex, {name, description, rule}>
 */
export function planEmissions(clusters, allFindings, outDir, llmRefinements = new Map()) {
  const interrogationLines = [];
  const plan = [];

  for (const [idx, cluster] of clusters.entries()) {
    const findings = cluster.indices.map((i) => allFindings[i]);
    const route = cluster.route;
    const name = safeArtifactStem(cluster.name);
    const refinement = llmRefinements.get(idx) ?? null;
    const files = [];

    if (route === 'lint') {
      files.push(buildLintDescriptor(name, findings));
      files.push(buildCheckScript(name, findings));
    } else if (route === 'skill') {
      files.push(buildSkillStub(name, findings, refinement));
    } else {
      // spec-gap — collect lines for interrogation-template.md
      interrogationLines.push(buildSpecGapLine(name, findings));
    }

    // Apply outDir prefix
    const prefixedFiles = files.map((f) => ({
      ...f,
      path: `${outDir}/${f.path}`,
    }));

    plan.push({
      cluster,
      route,
      files: prefixedFiles,
      destination:
        route === 'lint'
          ? `${outDir}/${name}.lint.json + ${outDir}/check-${name}.mjs`
          : route === 'skill'
            ? `${outDir}/${name}.SKILL.md`
            : `${outDir}/interrogation-template.md`,
    });
  }

  // Merge spec-gap lines into interrogation-template.md
  if (interrogationLines.length > 0) {
    const templatePath = `${outDir}/interrogation-template.md`;
    plan
      .filter((p) => p.route === 'spec-gap')
      .forEach((p) => {
        // All spec-gap entries share the same interrogation template file
        p.interrogationPath = templatePath;
      });

    // Add interrogation template as a synthetic "cluster" file entry
    plan.push({
      cluster: null,
      route: 'spec-gap-template',
      files: [
        {
          path: templatePath,
          content:
            `# Interrogation Template\n\n` +
            `Auto-generated by lesson-foundry. Answer these questions in your spec (P1).\n\n` +
            interrogationLines.join(''),
          append: true,
        },
      ],
      destination: templatePath,
    });
  }

  return plan;
}
