#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildSync, version as esbuildVersion } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function metadataSource({
  pluginVersion,
  bundledDependencies,
  esbuildVersion: builderVersion,
}) {
  return `// GENERATED FILE — run \`npm run build:cursor-mcp\`; do not edit directly.
// Bundled into the Cursor MCP launcher so plugin-cache startup needs no
// package.json read and no node_modules tree.

const SOURCE_MCP_BUILD_METADATA = Object.freeze({
  pluginVersion: '${pluginVersion}',
  bundledDependencies: Object.freeze(${JSON.stringify(bundledDependencies, null, 2).replaceAll("\n", "\n  ")}),
  esbuildVersion: '${builderVersion}',
});

export const MCP_BUILD_METADATA = typeof __ADLC_MCP_BUILD_METADATA__ === 'undefined'
  ? SOURCE_MCP_BUILD_METADATA
  : Object.freeze(__ADLC_MCP_BUILD_METADATA__);
`;
}

/**
 * Build the self-contained Cursor MCP launcher from one official code path.
 * With write=false, returns exact generated bytes without touching the tree.
 */
export function buildCursorMcp({
  root = ROOT,
  write = true,
  buildSyncImpl = buildSync,
} = {}) {
  const plugin = join(root, "plugins", "adlc-cursor");
  const metadataPath = join(plugin, "lib", "mcp-build-metadata.mjs");
  const entryPath = join(plugin, "bin", "adlc-mcp-wrapper.mjs");
  const outputPath = join(plugin, "bin", "adlc-mcp-wrapper.bundle.mjs");
  const bundledPackages = Object.freeze({
    "@adlc/core": join(root, "packages", "core", "package.json"),
    "@adlc/tickets": join(root, "packages", "tickets", "package.json"),
  });

  const rootPackage = readJson(join(root, "package.json"));
  const pluginPackage = readJson(join(plugin, "package.json"));
  const declaredEsbuildVersion = rootPackage.devDependencies?.esbuild;
  if (declaredEsbuildVersion !== esbuildVersion) {
    throw new Error(
      `esbuild version mismatch: package.json declares ${declaredEsbuildVersion ?? "<missing>"}, ` +
        `but the loaded version is ${esbuildVersion}. Run npm install, then npm run build:cursor-mcp.`,
    );
  }

  const bundledDependencies = {};
  for (const [name, packagePath] of Object.entries(bundledPackages)) {
    const bundledPackage = readJson(packagePath);
    const expectedRange = `^${bundledPackage.version}`;
    const declaredRange = pluginPackage.dependencies?.[name];
    if (
      bundledPackage.version !== pluginPackage.version ||
      declaredRange !== expectedRange
    ) {
      throw new Error(
        `${name} bundle lockstep mismatch: plugin=${pluginPackage.version}, package=${bundledPackage.version}, ` +
          `declared=${declaredRange ?? "<missing>"}, expected=${expectedRange}`,
      );
    }
    bundledDependencies[name] = bundledPackage.version;
  }

  const metadataValue = {
    pluginVersion: pluginPackage.version,
    bundledDependencies,
    esbuildVersion,
  };
  const metadata = Buffer.from(metadataSource(metadataValue));
  const result = buildSyncImpl({
    absWorkingDir: root,
    entryPoints: [entryPath],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node18",
    outfile: outputPath,
    write: false,
    define: {
      __ADLC_MCP_BUILD_METADATA__: JSON.stringify(metadataValue),
    },
  });
  const outputFile =
    result.outputFiles?.find((file) => file.path === outputPath) ??
    result.outputFiles?.[0];
  if (!outputFile) {
    throw new Error("esbuild returned no Cursor MCP bundle output");
  }
  const bundle = Buffer.from(outputFile.contents);

  if (write) {
    writeFileSync(metadataPath, metadata);
    writeFileSync(outputPath, bundle);
  }

  return Object.freeze({
    metadata,
    bundle,
    metadataPath,
    outputPath,
  });
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  buildCursorMcp();
}
