#!/usr/bin/env node

import { existsSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { buildSync, version as esbuildVersion } from "esbuild";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function metadataSource({
  pluginVersion,
  bundledDependencies,
  esbuildVersion: builderVersion,
}) {
  return `// GENERATED FILE — run \`npm run build:cursor-mcp\`; do not edit directly.
// Bundled into the Cursor MCP launcher so plugin-cache startup needs no
// package.json read and no node_modules tree.

const SOURCE_MCP_BUILD_METADATA = Object.freeze({
  pluginVersion: '${pluginVersion}',
  bundledDependencies: Object.freeze(${JSON.stringify(bundledDependencies, null, 2).replaceAll("\n", "\n  ")}),
  esbuildVersion: '${builderVersion}',
});

export const MCP_BUILD_METADATA = typeof __ADLC_MCP_BUILD_METADATA__ === 'undefined'
  ? SOURCE_MCP_BUILD_METADATA
  : Object.freeze(__ADLC_MCP_BUILD_METADATA__);
`;
}

export const CURSOR_HOOK_NAMES = Object.freeze([
  "adlc-session-start",
  "adlc-pretool",
  "adlc-audit",
  "adlc-shell-advisory",
  "adlc-precompact",
  "adlc-subagent",
  "adlc-stop",
  "adlc-preflight",
]);

export const CURSOR_HOOK_BUNDLES = Object.freeze(
  CURSOR_HOOK_NAMES.map((name) => `plugins/adlc-cursor/hooks/${name}.bundle.mjs`),
);

function bundleEntry({ root, entryPath, outputPath, label, metadataValue, buildSyncImpl }) {
  const result = buildSyncImpl({
    absWorkingDir: root,
    entryPoints: [entryPath],
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node18",
    outfile: outputPath,
    write: false,
    define: {
      __ADLC_MCP_BUILD_METADATA__: JSON.stringify(metadataValue),
    },
  });
  const outputFile =
    result.outputFiles?.find((file) => file.path === outputPath) ??
    result.outputFiles?.[0];
  if (!outputFile) {
    throw new Error(`esbuild returned no ${label} bundle output`);
  }
  return Buffer.from(outputFile.contents);
}

function publishAtomically(entries, { writeFileSyncImpl = writeFileSync, renameSyncImpl = renameSync } = {}) {
  const staged = [];
  const snapshots = entries.map(({ target }) =>
    existsSync(target)
      ? { target, existed: true, previous: readFileSync(target) }
      : { target, existed: false, previous: null },
  );
  const committed = [];
  try {
    for (let i = 0; i < entries.length; i += 1) {
      const { target, contents } = entries[i];
      const tempPath = `${target}.tmp-${process.pid}-${i}`;
      writeFileSyncImpl(tempPath, contents);
      staged.push({ tempPath, target, snapshot: snapshots[i] });
    }
    for (const item of staged) {
      renameSyncImpl(item.tempPath, item.target);
      committed.push(item);
    }
  } catch (err) {
    for (let i = committed.length - 1; i >= 0; i -= 1) {
      const { target, snapshot } = committed[i];
      try {
        if (snapshot.existed) writeFileSync(target, snapshot.previous);
        else rmSync(target, { force: true });
      } catch {
        /* best-effort rollback */
      }
    }
    throw err;
  } finally {
    for (const { tempPath } of staged) {
      rmSync(tempPath, { force: true });
    }
  }
}

/**
 * Build the self-contained Cursor MCP launcher and all 8 Cursor hook bundles
 * from one official code path. With write=false, returns exact generated bytes
 * without touching the tree.
 */
export function buildCursorMcp({
  root = ROOT,
  write = true,
  buildSyncImpl = buildSync,
  writeFileSyncImpl = writeFileSync,
  renameSyncImpl = renameSync,
} = {}) {
  const plugin = join(root, "plugins", "adlc-cursor");
  const metadataPath = join(plugin, "lib", "mcp-build-metadata.mjs");
  const entryPath = join(plugin, "bin", "adlc-mcp-wrapper.mjs");
  const outputPath = join(plugin, "bin", "adlc-mcp-wrapper.bundle.mjs");
  const bundledPackages = Object.freeze({
    "@adlc/core": join(root, "packages", "core", "package.json"),
    "@adlc/tickets": join(root, "packages", "tickets", "package.json"),
    "@adlc/build-gate": join(root, "packages", "build-gate", "package.json"),
    "@adlc/flail-detector": join(root, "packages", "flail-detector", "package.json"),
  });

  const rootPackage = readJson(join(root, "package.json"));
  const pluginPackage = readJson(join(plugin, "package.json"));
  const declaredEsbuildVersion = rootPackage.devDependencies?.esbuild;
  if (declaredEsbuildVersion !== esbuildVersion) {
    throw new Error(
      `esbuild version mismatch: package.json declares ${declaredEsbuildVersion ?? "<missing>"}, ` +
        `but the loaded version is ${esbuildVersion}. Run npm install, then npm run build:cursor-mcp.`,
    );
  }

  const mcpBundledNames = new Set(["@adlc/core", "@adlc/tickets"]);
  const bundledDependencies = {};
  for (const [name, packagePath] of Object.entries(bundledPackages)) {
    const bundledPackage = readJson(packagePath);
    const expectedRange = `^${bundledPackage.version}`;
    const declaredRange = pluginPackage.dependencies?.[name];
    if (
      bundledPackage.version !== pluginPackage.version ||
      declaredRange !== expectedRange
    ) {
      throw new Error(
        `${name} bundle lockstep mismatch: plugin=${pluginPackage.version}, package=${bundledPackage.version}, ` +
          `declared=${declaredRange ?? "<missing>"}, expected=${expectedRange}`,
      );
    }
    if (mcpBundledNames.has(name)) {
      bundledDependencies[name] = bundledPackage.version;
    }
  }

  const metadataValue = {
    pluginVersion: pluginPackage.version,
    bundledDependencies,
    esbuildVersion,
  };
  const metadata = Buffer.from(metadataSource(metadataValue));
  const bundle = bundleEntry({
    root,
    entryPath,
    outputPath,
    label: "Cursor MCP",
    metadataValue,
    buildSyncImpl,
  });

  const hookBundles = {};
  const hookOutputs = [];
  for (const name of CURSOR_HOOK_NAMES) {
    const hookEntryPath = join(plugin, "hooks", `${name}.mjs`);
    const hookOutputPath = join(plugin, "hooks", `${name}.bundle.mjs`);
    const relPath = `plugins/adlc-cursor/hooks/${name}.bundle.mjs`;
    const contents = bundleEntry({
      root,
      entryPath: hookEntryPath,
      outputPath: hookOutputPath,
      label: `Cursor hook (${name})`,
      metadataValue,
      buildSyncImpl,
    });
    hookBundles[relPath] = contents;
    hookOutputs.push({ outputPath: hookOutputPath, contents });
  }

  // Stage every artifact to a sibling temp file and atomically rename them into
  // place with rollback on failure so a partial write never leaves a mixed set.
  if (write) {
    publishAtomically(
      [
        { target: metadataPath, contents: metadata },
        { target: outputPath, contents: bundle },
        ...hookOutputs.map((hook) => ({ target: hook.outputPath, contents: hook.contents })),
      ],
      { writeFileSyncImpl, renameSyncImpl },
    );
  }

  return Object.freeze({
    metadata,
    bundle,
    metadataPath,
    outputPath,
    hookBundles: Object.freeze(hookBundles),
  });
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  buildCursorMcp();
}
