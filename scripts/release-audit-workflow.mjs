#!/usr/bin/env node
// release-audit-workflow — build the runnable workflow script for /release-audit.
//
// WHY THIS EXISTS. The Workflow tool takes its input either as `args`, which must
// be written inline into the tool call, or as a script file. The collected document
// is tens of kilobytes even after projection, so the `args` route means transcribing
// that JSON by hand on every run — expensive, and a silent-corruption risk if a
// single character is mistyped. Emitting a self-contained script sidesteps both: the
// document is embedded from disk, byte-exact, and the tool is handed a path.
//
// The skill's canonical script lives in a markdown fence
// (.claude/skills/release-audit/references/workflow-script.md) so that it is
// reviewable prose-adjacent and is not mistaken for a module the test runner should
// execute. This reads that fence, prepends the document, and writes the result.
//
// Usage:
//   node scripts/release-audit-workflow.mjs --input <wargs.json> --out <workflow.mjs>

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { realpathSync } from 'node:fs';

const ROOT = join(dirname(dirname(fileURLToPath(import.meta.url))));

export const WORKFLOW_MD = '.claude/skills/release-audit/references/workflow-script.md';

export function parseArgs(argv) {
  const out = { input: null, out: null };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--input') { out.input = argv[i + 1] ?? null; i += 1; continue; }
    if (argv[i] === '--out') { out.out = argv[i + 1] ?? null; i += 1; }
  }
  return out;
}

/**
 * The single ```javascript fence in the skill's workflow reference.
 *
 * Exactly one is required. Two would make "which block runs" a guess, and the
 * wrong guess produces a workflow that looks plausible and audits nothing.
 */
export function extractScript(markdown) {
  const blocks = [...String(markdown).matchAll(/```javascript\n([\s\S]*?)\n```/g)].map((m) => m[1]);
  if (blocks.length !== 1) {
    throw new Error(`expected exactly one javascript block in ${WORKFLOW_MD}, found ${blocks.length}`);
  }
  return blocks[0];
}

/**
 * Prepend the collected document to the script as `INPUT_DOC`.
 *
 * JSON.stringify output is a JavaScript expression for every value JSON.parse can
 * produce, with one exception that matters here: `</script` and U+2028/U+2029 are
 * legal in JSON strings and hostile in a script context. Issue titles are attacker-
 * adjacent text — anyone can open an issue — and they land in this file verbatim, so
 * they are escaped rather than trusted.
 */
export function buildScript(doc, script) {
  const json = JSON.stringify(doc)
    .replace(/</g, '\\u003c')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
  return `// Generated by scripts/release-audit-workflow.mjs — do not edit.\n`
    + `// Source: ${WORKFLOW_MD}\n`
    + `const INPUT_DOC = ${json}\n\n${script}\n`;
}

export function workflowMain(argv = process.argv.slice(2), { readFile = readFileSync, writeFile = writeFileSync, log = console.log, root = ROOT } = {}) {
  const args = parseArgs(argv);
  if (!args.input || !args.out) {
    log('usage: release-audit-workflow --input <wargs.json> --out <workflow.mjs>');
    return 1;
  }
  const doc = JSON.parse(readFile(args.input, 'utf8'));
  const script = extractScript(readFile(join(root, WORKFLOW_MD), 'utf8'));
  const built = buildScript(doc, script);
  writeFile(args.out, built);
  log(`wrote ${args.out} (${built.length} bytes, ${doc.units?.length ?? 0} units)`);
  return 0;
}

const invokedDirectly = process.argv[1]
  && realpathSync(fileURLToPath(import.meta.url)) === realpathSync(process.argv[1]);
if (invokedDirectly) process.exit(workflowMain());
